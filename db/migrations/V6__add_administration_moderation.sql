ALTER TABLE public.servico
    ADD COLUMN visivel_catalogo boolean NOT NULL DEFAULT true;

CREATE INDEX servico_catalogo_visivel_ix
    ON public.servico (id_servico)
    WHERE ativo AND visivel_catalogo;

CREATE TABLE public.historico_moderacao (
    id_historico_moderacao bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_administrador integer NOT NULL,
    id_usuario_alvo integer,
    id_servico_alvo integer,
    acao varchar(32) NOT NULL CHECK (
        acao IN (
            'CONTA_DESATIVADA',
            'CONTA_REATIVADA',
            'SERVICO_OCULTADO',
            'SERVICO_RESTAURADO'
        )
    ),
    motivo varchar(500) NOT NULL CHECK (length(trim(motivo)) > 0),
    data_hora timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT historico_moderacao_admin_fk
        FOREIGN KEY (id_administrador) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT historico_moderacao_usuario_fk
        FOREIGN KEY (id_usuario_alvo) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT historico_moderacao_servico_fk
        FOREIGN KEY (id_servico_alvo) REFERENCES public.servico (id_servico)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT historico_moderacao_alvo_ck CHECK (
        (
            acao IN ('CONTA_DESATIVADA', 'CONTA_REATIVADA')
            AND id_usuario_alvo IS NOT NULL
            AND id_servico_alvo IS NULL
        )
        OR
        (
            acao IN ('SERVICO_OCULTADO', 'SERVICO_RESTAURADO')
            AND id_usuario_alvo IS NULL
            AND id_servico_alvo IS NOT NULL
        )
    )
);

CREATE INDEX historico_moderacao_tempo_ix
    ON public.historico_moderacao (data_hora, id_historico_moderacao);
CREATE INDEX historico_moderacao_usuario_ix
    ON public.historico_moderacao (id_usuario_alvo, data_hora)
    WHERE id_usuario_alvo IS NOT NULL;
CREATE INDEX historico_moderacao_servico_ix
    ON public.historico_moderacao (id_servico_alvo, data_hora)
    WHERE id_servico_alvo IS NOT NULL;

CREATE FUNCTION public.impedir_alteracao_historico_moderacao()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'historico_moderacao e imutavel'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER historico_moderacao_imutavel_trg
    BEFORE UPDATE OR DELETE ON public.historico_moderacao
    FOR EACH ROW EXECUTE FUNCTION public.impedir_alteracao_historico_moderacao();
