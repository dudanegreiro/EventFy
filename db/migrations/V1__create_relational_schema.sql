CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE public.usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL CHECK (length(trim(nome)) > 0),
    email varchar(254) NOT NULL,
    senha_hash varchar(255) NOT NULL CHECK (length(senha_hash) > 0),
    tipo_usuario varchar(20) NOT NULL
        CHECK (tipo_usuario IN ('ORGANIZADOR', 'PRESTADOR', 'ADMINISTRADOR')),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX usuario_email_lower_uk ON public.usuario (lower(email));

CREATE TABLE public.evento (
    id_evento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organizador integer NOT NULL,
    nome varchar(160) NOT NULL CHECK (length(trim(nome)) > 0),
    descricao text,
    data_inicio timestamptz NOT NULL,
    data_fim timestamptz NOT NULL,
    local varchar(200) NOT NULL CHECK (length(trim(local)) > 0),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT evento_organizador_fk
        FOREIGN KEY (id_organizador) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT evento_periodo_ck CHECK (data_fim > data_inicio)
);

CREATE INDEX evento_organizador_ix ON public.evento (id_organizador);

CREATE TABLE public.servico (
    id_servico integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestador integer NOT NULL,
    nome varchar(160) NOT NULL CHECK (length(trim(nome)) > 0),
    categoria varchar(80) NOT NULL CHECK (length(trim(categoria)) > 0),
    descricao text,
    preco numeric(12, 2) NOT NULL CHECK (preco >= 0),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT servico_prestador_fk
        FOREIGN KEY (id_prestador) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX servico_prestador_ix ON public.servico (id_prestador);
CREATE INDEX servico_catalogo_ix ON public.servico (categoria, preco) WHERE ativo;

CREATE TABLE public.disponibilidade_servico (
    id_disponibilidade integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servico integer NOT NULL,
    data_inicio timestamptz NOT NULL,
    data_fim timestamptz NOT NULL,
    tipo varchar(24) NOT NULL CHECK (
        tipo IN ('DISPONIVEL', 'BLOQUEIO_MANUAL', 'RESERVA')
    ),
    motivo varchar(500),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT disponibilidade_servico_fk
        FOREIGN KEY (id_servico) REFERENCES public.servico (id_servico)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT disponibilidade_periodo_ck CHECK (data_fim > data_inicio)
);

CREATE INDEX disponibilidade_servico_periodo_ix
    ON public.disponibilidade_servico (id_servico, data_inicio, data_fim)
    WHERE ativo;

CREATE TABLE public.arquivo (
    id_arquivo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_servico integer NOT NULL,
    nome_original varchar(255) NOT NULL CHECK (length(trim(nome_original)) > 0),
    url varchar(2048) NOT NULL CHECK (length(trim(url)) > 0),
    tipo_mime varchar(127) NOT NULL CHECK (
        tipo_mime IN (
            'image/jpeg',
            'image/png',
            'image/webp',
            'application/pdf',
            'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
        )
    ),
    tamanho bigint NOT NULL CHECK (tamanho > 0 AND tamanho <= 10000000),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT arquivo_servico_fk
        FOREIGN KEY (id_servico) REFERENCES public.servico (id_servico)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX arquivo_servico_ix ON public.arquivo (id_servico) WHERE ativo;

CREATE TABLE public.reserva (
    id_reserva integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento integer NOT NULL,
    id_servico integer NOT NULL,
    id_solicitante integer NOT NULL,
    status varchar(20) NOT NULL CHECK (
        status IN (
            'SOLICITADA',
            'EM_ANALISE',
            'APROVADA',
            'CONFIRMADA',
            'RECUSADA',
            'CANCELADA',
            'EXPIRADA',
            'FINALIZADA'
        )
    ),
    data_inicio timestamptz NOT NULL,
    data_fim timestamptz NOT NULL,
    observacao text,
    motivo_recusa text,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT reserva_evento_fk
        FOREIGN KEY (id_evento) REFERENCES public.evento (id_evento)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT reserva_servico_fk
        FOREIGN KEY (id_servico) REFERENCES public.servico (id_servico)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT reserva_solicitante_fk
        FOREIGN KEY (id_solicitante) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT reserva_periodo_ck CHECK (data_fim > data_inicio),
    CONSTRAINT reserva_motivo_recusa_ck
        CHECK (status <> 'RECUSADA' OR length(trim(coalesce(motivo_recusa, ''))) > 0)
);

ALTER TABLE public.reserva
    ADD CONSTRAINT reserva_sem_sobreposicao_ativa
    EXCLUDE USING gist (
        id_servico WITH =,
        tstzrange(data_inicio, data_fim, '[)') WITH &&
    )
    WHERE (
        ativo
        AND status IN ('SOLICITADA', 'EM_ANALISE', 'APROVADA', 'CONFIRMADA')
    );

CREATE INDEX reserva_evento_ix ON public.reserva (id_evento);
CREATE INDEX reserva_servico_ix ON public.reserva (id_servico);
CREATE INDEX reserva_solicitante_ix ON public.reserva (id_solicitante);
CREATE INDEX reserva_status_ix ON public.reserva (status);

CREATE TABLE public.historico_reserva (
    id_historico integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva integer NOT NULL,
    id_usuario integer,
    status_anterior varchar(20) CHECK (
        status_anterior IS NULL
        OR status_anterior IN (
            'SOLICITADA',
            'EM_ANALISE',
            'APROVADA',
            'CONFIRMADA',
            'RECUSADA',
            'CANCELADA',
            'EXPIRADA',
            'FINALIZADA'
        )
    ),
    status_novo varchar(20) NOT NULL CHECK (
        status_novo IN (
            'SOLICITADA',
            'EM_ANALISE',
            'APROVADA',
            'CONFIRMADA',
            'RECUSADA',
            'CANCELADA',
            'EXPIRADA',
            'FINALIZADA'
        )
    ),
    data_hora timestamptz NOT NULL DEFAULT now(),
    observacao text,
    motivo text,
    CONSTRAINT historico_reserva_fk
        FOREIGN KEY (id_reserva) REFERENCES public.reserva (id_reserva)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT historico_usuario_fk
        FOREIGN KEY (id_usuario) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX historico_reserva_tempo_ix
    ON public.historico_reserva (id_reserva, data_hora, id_historico);

CREATE FUNCTION public.impedir_alteracao_historico_reserva()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'historico_reserva e imutavel'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER historico_reserva_imutavel_trg
    BEFORE UPDATE OR DELETE ON public.historico_reserva
    FOR EACH ROW EXECUTE FUNCTION public.impedir_alteracao_historico_reserva();

CREATE TABLE public.avaliacao (
    id_avaliacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva integer NOT NULL UNIQUE,
    id_avaliador integer NOT NULL,
    nota smallint NOT NULL CHECK (nota BETWEEN 1 AND 5),
    criado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT avaliacao_reserva_fk
        FOREIGN KEY (id_reserva) REFERENCES public.reserva (id_reserva)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT avaliacao_avaliador_fk
        FOREIGN KEY (id_avaliador) REFERENCES public.usuario (id_usuario)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);
